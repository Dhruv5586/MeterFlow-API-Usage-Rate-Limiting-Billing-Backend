"""
Payment & Webhook Pydantic Schemas
----------------------------------
Validation models for Razorpay order generation, signature verification,
payment status inspection, and webhook processing.
"""

import uuid
from decimal import Decimal
from typing import Optional
from datetime import datetime
from pydantic import BaseModel, Field, ConfigDict


class PaymentOrderCreateRequest(BaseModel):
    """Request payload to initiate a Razorpay payment order for an open invoice."""
    invoice_id: uuid.UUID = Field(..., description="UUID of the payable invoice")


class PaymentOrderResponse(BaseModel):
    """
    Public order metadata returned to the frontend client to initialize Razorpay checkout.
    Amount is expressed in minor units (e.g. cents/paise) as required by Razorpay.
    """
    order_id: str = Field(..., description="Razorpay order identifier (e.g. order_xxx)")
    amount: int = Field(..., description="Payment amount in integer minor units (e.g. 2900 for $29.00)")
    currency: str = Field(..., description="ISO 4217 currency code (e.g. USD, INR)")
    key_id: str = Field(..., description="Public Razorpay Key ID for client checkout")
    invoice_id: uuid.UUID = Field(..., description="UUID of the invoice being paid")
    invoice_number: str = Field(..., description="Human-readable invoice identifier")


class PaymentVerifyRequest(BaseModel):
    """
    Client payment verification payload sent following checkout completion.
    Must contain order ID, payment ID, and HMAC-SHA256 signature generated by Razorpay.
    """
    razorpay_order_id: str = Field(..., description="Razorpay Order ID")
    razorpay_payment_id: str = Field(..., description="Razorpay Payment ID")
    razorpay_signature: str = Field(..., description="HMAC-SHA256 signature from Razorpay")


class PaymentResponse(BaseModel):
    """Complete payment ledger record."""
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    user_id: uuid.UUID
    invoice_id: uuid.UUID
    razorpay_order_id: str
    razorpay_payment_id: Optional[str] = None
    amount: Decimal
    currency: str
    status: str
    method: Optional[str] = None
    error_code: Optional[str] = None
    error_description: Optional[str] = None
    captured_at: Optional[datetime] = None
    refunded_at: Optional[datetime] = None
    amount_refunded: Decimal = Decimal("0.00")
    created_at: datetime
    updated_at: datetime


class WebhookResponse(BaseModel):
    """Acknowledgment payload returned to Razorpay webhook dispatcher."""
    status: str
    message: str
    event_id: Optional[str] = None
    event_type: Optional[str] = None
